    /// <summary>The name a tag hashes from, when the executable names it.</summary>
    public static bool TryGetName(uint tag, out string name)
    {
        return ByTag.Value.TryGetValue(tag, out name!);
    }

    /// <summary>The name without its extension when known, else <c>tag_XXXXXXXX</c>.</summary>
    public static string NameOrTag(uint tag)
    {
        if (!TryGetName(tag, out var name))
        {
            return $"tag_{tag:X8}";
        }

        var slash = name.LastIndexOf('/');
        var file = slash < 0 ? name : name[(slash + 1)..];
        var dot = file.LastIndexOf('.');
        return dot <= 0 ? file : file[..dot];
    }

    private static Dictionary<uint, string> Build()
    {
        var byTag = new Dictionary<uint, string>(Names.Count);
        foreach (var name in Names)
        {
            byTag.TryAdd(BosAssetHash.Compute(name), name);
        }

        return byTag;
    }
