    /// <summary>
    ///     Decode-position to natural-order permutation.
    ///     <c>natural[n] = decoded[CoefficientPermutation[n]]</c>, natural indexed <c>row*8+col</c>.
    ///     This is NOT a zig-zag and must not be derived - position 44 lands on natural row 2
    ///     column 2. <c>[0] == 0</c>, so the DC always lands at natural index 0.
    ///     <para>
    ///         PROVENANCE. This is the ONE table here that is not a contiguous run of bytes in
    ///         <c>binkw32.dll</c> - searching the whole 291,328-byte image finds not even its first
    ///         8 bytes. It lives in CODE, in the epilogue of the coefficient reader FUN_3001CE50 at
    ///         <c>0x3001D6E3 .. 0x3001D7F3</c>, which copies the decode-order scratch at
    ///         <c>esp+0x30</c> (written by <c>mov word ptr [esp+ecx*2+0x30], ax</c> at
    ///         <c>0x3001D6B9</c>, <c>ecx</c> = decode position) into the caller's 64-entry int16
    ///         block. Each <c>mov dword ptr [eax+D], reg</c> moves TWO coefficients, so
    ///         <c>natural[D/2 + k] = decoded[(S-0x30)/2 + k]</c> for the esp offset <c>S</c> the
    ///         register was loaded from.
    ///     </para>
    ///     <para>
    ///         ⚠⚠ THE TRAP: three <c>pop</c>s are INTERLEAVED into that copy (<c>pop edi</c> at
    ///         <c>0x3001D7C5</c>, <c>pop esi</c> at <c>0x3001D7D7</c>, <c>pop ebp</c> at
    ///         <c>0x3001D7EC</c>), so <c>esp</c> drifts 0 -> 4 -> 8 -> 0xC part-way through and the
    ///         later loads mean something different from what their printed offsets say. Reading
    ///         the block naively, without tracking that drift, gets 8 of the 64 entries wrong -
    ///         which is the control: a mechanical walk that accounts for the pops reproduces this
    ///         table 64/64 exactly, and the same walk without them does not.
