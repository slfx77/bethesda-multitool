/// <summary>
///     The checked-in cut-1c cover manifest against its contract, without any real asset: the parser's rules (each with
///     a synthetic manifest that breaks exactly one), and the manifest facts the plan measured (plan
///     <c>docs/design/cut1c-xngine-reader-plan-20260925.md</c>, section 9 "Cover"), each digest pinned here
///     independently of the manifest file so a regenerated manifest that drops a row, moves a pin to another copy, or
///     swaps the BARSTEP1 namesake pair fails without any game install present.
/// </summary>
/// <remarks>
///     The folded-fan row is pinned to M-Z's pick (3D.BSA CAT02.3D #1111), so a regeneration that reverts to
///     another pick fails here without any game install present.
///     The independent pins were re-measured from the retail containers on 2026-09-28 by
///     <c>TestOutput/cut1c-20260928/slice12/slice1/cut1c_cover_manifest.py</c> (fresh slicing code; 28 of 28 rows
///     reproduced the digests the plan quotes, LZSS payload and stored digests separately). The BARSTEP1 pair is the
///     slice-1 control's heart: the 3D.BSA namesake (#438) has the SAME payload size as the 3D.BS6 cover entry
///     (#437), 1,540 bytes, so only the digests separate them; a size-only comparison cannot.
///     The slice-5 review (2026-09-28) added three edge rows, regenerated by
///     <c>TestOutput/cut1c-20260928/slice56/cut1c_cover_manifest.py</c> (31 of 31 rows reproduced): ARCH3D 409, where
///     the D2 unfold changes stored values; 3D.BSA PUZSPRT1.3D, a face that repeats a source point; and NECRISLE.ROB
///     NCGATE01, both a repeated-point face and the Redguard values only the legacy route unfolds.
/// </remarks>
