    [Fact]
    public void Parse_ReadsRolesControlsAndStoredPins()
    {
        var files = Cut1cCoverManifest.Parse(Manifest());
        Assert.Equal(2, files.Count);
        var loose = files[0];
        Assert.Equal(Cut1cCoverFile.LooseContainer, loose.Container);
        Assert.Null(loose.Index);
        Assert.False(loose.IsCompressed);
        Assert.Equal("the control", Assert.Single(loose.Controls));
        var archive = files[1];
        Assert.True(archive.IsCompressed);
        Assert.Equal(9L, archive.StoredSize);
        Assert.Equal(StoredSha, archive.StoredSha256);
        Assert.Equal(3, archive.Index);
        Assert.Single(archive.Candidates);
    }

