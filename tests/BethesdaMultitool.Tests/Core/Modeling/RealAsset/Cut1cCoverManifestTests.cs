    private static string RobManifest(string segmentType)
    {
        return """
            {
             "tool": "cut1c_cover_manifest.py",
             "manifestSchema": 1,
             "options": {"scope": "cut1c", "payloads": true},
             "files": [
              {"role": "design", "name": "ROBROW", "game": "Redguard", "population": "redguard_rob_3dart",
               "container": "rob", "source": "Sample/a/D.ROB", "entry": "SEG0", "index": 0, "tag": "v2.7",
               "size": 10, "sha256": "LOOSESHA"SEGMENT, "alsoIn": [], "controls": [], "note": "n"}
             ]
            }
            """
            .Replace("LOOSESHA", LooseSha, StringComparison.Ordinal)
            .Replace("SEGMENT", segmentType, StringComparison.Ordinal);
    }

    private static string Manifest(string scope = Cut1cCoverManifest.Scope, string role = "design",
        string looseIndex = "null", string archiveIndex = "3", long looseSize = 10, string? declined = null,
        string alsoIn = "", string controls2 = "", string segmentType1 = "")
    {
        return ManifestJson
            .Replace("SCOPE", scope, StringComparison.Ordinal)
            .Replace("ROLE", role, StringComparison.Ordinal)
            .Replace("LOOSEINDEX", looseIndex, StringComparison.Ordinal)
            .Replace("ARCHIVEINDEX", archiveIndex, StringComparison.Ordinal)
            .Replace("LOOSESIZE", looseSize.ToString(System.Globalization.CultureInfo.InvariantCulture),
                StringComparison.Ordinal)
            .Replace("LOOSESHA", LooseSha, StringComparison.Ordinal)
            .Replace("ARCHIVESHA", ArchiveSha, StringComparison.Ordinal)
            .Replace("STOREDSIZE", "9", StringComparison.Ordinal)
            .Replace("STOREDSHA", "\"" + StoredSha + "\"", StringComparison.Ordinal)
            .Replace("CONTROLS1", "{\"name\": \"the control\"}", StringComparison.Ordinal)
            .Replace("CONTROLS2", controls2, StringComparison.Ordinal)
            .Replace("DECLINED1",
                declined is null ? "" : ", \"declined\": \"" + declined + "\"", StringComparison.Ordinal)
            .Replace("SEGTYPE1", segmentType1, StringComparison.Ordinal)
            .Replace("ALSOIN", alsoIn, StringComparison.Ordinal);
    }
