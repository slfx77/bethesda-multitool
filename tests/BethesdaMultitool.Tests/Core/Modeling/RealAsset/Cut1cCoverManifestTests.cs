    /// <summary>
    ///     The slice-5 review rows, each pinned here by container, index and digest so a regeneration that moves one fails
    ///     without any game install present: ARCH3D 409 (index 4762, 57,176 bytes), 3D.BSA PUZSPRT1.3D (#98, 15,650
    ///     decoded bytes, LZSS 5,274) and NECRISLE.ROB NCGATE01 (segment 108, type 0, 7,506 bytes), which carries two
    ///     controls.
    /// </summary>
    [Fact]
    public void Manifest_PinsTheSlice5ReviewRows()
    {
        Assert.SkipWhen(Cut1cCoverManifest.Path is null, "The cut-1c cover manifest is not in this checkout.");
        var unfold = Cut1cCoverManifest.RequireControl("arch3d-unfold-changes-values");
        Assert.Equal(Cut1cCoverFile.Arch3dContainer, unfold.Container);
        Assert.Equal("409", unfold.Entry);
        Assert.Equal(4762, unfold.Index);
        Assert.Equal(57176, unfold.Size);
        Assert.Equal(Arch3d409Sha, unfold.Sha256);

        var bsa = Cut1cCoverManifest.RequireControl("bsa-repeated-point-plane");
        Assert.Equal(Cut1cCoverFile.XnGineBsaContainer, bsa.Container);
        Assert.Equal("PUZSPRT1.3D", bsa.Entry);
        Assert.Equal(98, bsa.Index);
        Assert.Equal(15650, bsa.Size);
        Assert.Equal(Puzsprt1Sha, bsa.Sha256);
        Assert.Equal(5274L, bsa.StoredSize);
        Assert.Equal(Puzsprt1StoredSha, bsa.StoredSha256);

        var rob = Cut1cCoverManifest.RequireControl("rob-repeated-point-planes");
        Assert.Same(rob, Cut1cCoverManifest.RequireControl("rob-legacy-unfold-accident"));
        Assert.Equal(Cut1cCoverFile.RobContainer, rob.Container);
        Assert.Equal("NCGATE01", rob.Entry);
        Assert.Equal(108, rob.Index);
        Assert.Equal(0, rob.SegmentType);
        Assert.Equal(7506, rob.Size);
        Assert.Equal(Ncgate01Sha, rob.Sha256);
    }

