    [Fact]
    public void Manifest_PinsTheBarstep1NamesakePairApartByDigestAlone()
    {
        Assert.SkipWhen(Cut1cCoverManifest.Path is null, "The cut-1c cover manifest is not in this checkout.");
        var cover = Cut1cCoverManifest.RequireControl("barstep1-bs6-cover");
        var namesake = Cut1cCoverManifest.RequireControl("barstep1-3dbsa-namesake");
        Assert.Equal(cover.Entry, namesake.Entry);
        Assert.Equal(437, cover.Index);
        Assert.Equal(438, namesake.Index);
        Assert.Equal(Barstep1Bs6Sha, cover.Sha256);
        Assert.Equal(Barstep1Bs6StoredSha, cover.StoredSha256);
        Assert.Equal(Barstep1NamesakeSha, namesake.Sha256);
        Assert.Equal(Barstep1NamesakeStoredSha, namesake.StoredSha256);

        // The pair has ONE payload size (1,540 bytes), so a size check cannot separate the copies; the digest must.
        Assert.Equal(cover.Size, namesake.Size);
        Assert.NotEqual(cover.Sha256, namesake.Sha256);
        Assert.NotEqual(cover.StoredSha256, namesake.StoredSha256);
    }

    [Fact]
    public void Manifest_PinsTheId5090GroupByIndex()
    {
        Assert.SkipWhen(Cut1cCoverManifest.Path is null, "The cut-1c cover manifest is not in this checkout.");
        var group = Cut1cCoverManifest.RequireGroup("id-5090-duplicate-group");
        Assert.Equal(6, group.Count);
        Assert.All(group, f => Assert.Equal("5090", f.Entry));
        Assert.Equal(new[] { 5007, 8903, 9787, 9824, 9826, 10238 },
            group.Select(f => f.Index!.Value).Order().ToArray());

        // 6 records, 5 distinct payloads: exactly the indices 5007 and 8903 are byte-identical.
        Assert.Equal(5, group.Select(f => f.Sha256).Distinct(StringComparer.Ordinal).Count());
        var twins = group.GroupBy(f => f.Sha256, StringComparer.Ordinal).Single(g => g.Count() > 1);
        Assert.Equal(new[] { 5007, 8903 }, twins.Select(f => f.Index!.Value).Order().ToArray());
    }

